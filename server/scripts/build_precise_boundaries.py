# ──────────────────────────────────────────────
# 1. Point-in-polygon（射线法）
# ──────────────────────────────────────────────

def point_in_polygon(pt, polygon):
    """
    射线法判断点是否在多边形内。
    polygon: 闭合环 [(lng,lat), ...]
    """
    x, y = pt
    inside = False
    n = len(polygon)
    j = n - 1
    for i in range(n):
        xi, yi = polygon[i]
        xj, yj = polygon[j]
        if ((yi > y) != (yj > y)) and (x < (xj - xi) * (y - yi) / (yj - yi) + xi):
            inside = not inside
        j = i
    return inside


def polygon_area(ring):
    """计算多边形面积（用于判断包含比例）"""
    area = 0
    n = len(ring)
    for i in range(n):
        x1, y1 = ring[i]
        x2, y2 = ring[(i + 1) % n]
        area += x1 * y2 - x2 * y1
    return abs(area) / 2


def filter_ring_by_clip(ring, clip_ring, keep_ratio=0.3):
    """
    过滤多边形环：只保留在 clip_ring 内部的点。
    如果超过 keep_ratio 的点在内，保留；否则丢弃。
    返回：过滤后的环，或 None
    """
    if not ring:
        return None
    
    # 测试每个点
    inside_pts = []
    for pt in ring:
        if point_in_polygon(pt, clip_ring):
            inside_pts.append(pt)
    
    ratio = len(inside_pts) / max(len(ring), 1)
    if ratio >= keep_ratio:
        return inside_pts
    return None


def filter_geometry(geom, clip_ring, keep_ratio=0.3):
    """
    过滤 Geometry（Polygon / MultiPolygon）。
    保留在 clip_ring 内部的比例 >= keep_ratio 的环。
    """
    if not clip_ring:
        return geom
    
    if geom['type'] == 'Polygon':
        rings = []
        for ring in geom['coordinates']:
            filtered = filter_ring_by_clip(ring, clip_ring, keep_ratio)
            if filtered:
                # 确保闭合
                if filtered[0] != filtered[-1]:
                    filtered.append(filtered[0])
                rings.append(filtered)
        if rings:
            return {'type': 'Polygon', 'coordinates': rings}
        return None
    
    elif geom['type'] == 'MultiPolygon':
        result = []
        for polygon in geom['coordinates']:
            poly_rings = []
            for ring in polygon:
                filtered = filter_ring_by_clip(ring, clip_ring, keep_ratio)
                if filtered:
                    if filtered[0] != filtered[-1]:
                        filtered.append(filtered[0])
                    poly_rings.append(filtered)
            if poly_rings:
                result.append(poly_rings)
        if result:
            return {'type': 'MultiPolygon', 'coordinates': result}
        return None
    
    return None


