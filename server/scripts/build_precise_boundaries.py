def build_entity(china_data, clip_ring, props):
    """从 china.json 裁剪出一个政权的高精度边界"""
    features_out = []
    
    for feat in china_data['features']:
        geom = feat['geometry']
        new_geom = filter_geometry(geom, clip_ring, keep_ratio=0.25)
        if new_geom:
            feat_props = {**props}
            feat_props['name'] = feat['properties'].get('name', '')
            features_out.append({
                'type': 'Feature',
                'properties': feat_props,
                'geometry': new_geom
            })
    
    return {
        'type': 'FeatureCollection',
        'properties': {
            'name': props['entity'],
            'color': props['color'],
            'fillOpacity': props.get('fillOpacity', 0.3),
        },
        'features': features_out
    }


