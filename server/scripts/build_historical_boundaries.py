    song1142 = build_feature_collection(
        [SOUTHERN_SONG_BOUNDARY], "南宋", "#E53935", 0.35)
    jin1142 = build_feature_collection(
        [JIN_BOUNDARY], "金", "#8E24AA", 0.30)

    # 大理（独立）
