def build_feature_collection(features, name, color, opacity):
    return {
        "type": "FeatureCollection",
        "properties": {
            "name": name,
            "color": color,
            "fillOpacity": opacity,
        },
        "features": features
    }


def main():
    # __file__ = server/scripts/build_historical_boundaries.py
    # 项目的 data 目录在 server/data/geo/historical/
    project_root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    output_dir = os.path.join(project_root, 'server', 'data', 'geo', 'historical')
    os.makedirs(output_dir, exist_ok=True)

    # 1111 年（北宋+辽+西夏）
    song1111 = build_feature_collection(
        [NORTHERN_SONG_BOUNDARY], "北宋", "#E53935", 0.35)
